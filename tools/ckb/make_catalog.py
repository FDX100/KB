#!/usr/bin/env python3
"""Writes shared/ckb_catalog.js from tools/ckb/catalog.json (English page string -> Sorani; {n} stands for a number kept as it is) and
lists the page strings (tools/preview/ckb_strings.json, made by COLLECT=1 node tools/preview/page_preview.js) that have no entry yet.

    python3 tools/ckb/make_catalog.py
"""
import json, os, re
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
cat = json.load(open(os.path.join(ROOT, 'tools', 'ckb', 'catalog.json'), encoding='utf-8'))
with open(os.path.join(ROOT, 'shared', 'ckb_catalog.js'), 'w', encoding='utf-8') as f:
    f.write("'use strict';\n// Generated by tools/ckb/make_catalog.py from tools/ckb/catalog.json: the app pages' English strings in Sorani (Central Kurdish).\n"
            'module.exports = ' + json.dumps(cat, ensure_ascii=False, indent=1) + ';\n')
print(len(cat), 'entries ->', 'shared/ckb_catalog.js')
p = os.path.join(ROOT, 'tools', 'preview', 'ckb_strings.json')
if os.path.exists(p):
    seen = json.load(open(p, encoding='utf-8'))
    skip = re.compile(r"^(\{n\}|--|[A-Za-z0-9 ./+-]*)$")
    miss = sorted({re.sub(r'\d[\d,.]*\d|\d', '{n}', s) for s in seen} - set(cat))
    miss = [m for m in miss if not skip.match(m) and 'quiet' not in m]
    print('without a translation (%d):' % len(miss))
    for m in miss: print('   ', m)
